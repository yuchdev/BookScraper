# --------------------------------------------------------------------------- #
# prune_html regression: every currently-matching selector survives pruning
# --------------------------------------------------------------------------- #
def _detail_fixture_params() -> list[Any]:
    params: list[Any] = []
    for site in DETAIL_SITES:
        for fixture in _detail_fixtures(site):
            params.append(pytest.param(site, fixture, id=f"{site}/{fixture.stem}"))
    return params


async def _count_matches(browser: Any, html: str, selectors: dict[str, str]) -> dict[str, int]:
    """Load ``html`` offline via set_content and return ``{field: match_count}`` for each selector."""
    page = await browser.new_page()
    try:
        await page.route("**/*", sd._block_all_requests)
        await page.set_content(html, wait_until="domcontentloaded")
        counts: dict[str, int] = {}
        for field, selector in selectors.items():
            try:
                counts[field] = await page.locator(selector).count()
            except Exception:  # noqa: BLE001 - a selector Playwright rejects simply does not count
                counts[field] = 0
        return counts
    finally:
        await page.close()


@pytest.mark.chromium
@pytest.mark.asyncio(loop_scope="session")
@pytest.mark.parametrize(("site", "fixture"), _detail_fixture_params())
async def test_pruning_preserves_every_currently_matching_selector(
    site: str,
    fixture: Path,
    chromium_browser: Any,
) -> None:
    """Scenario: every current detail selector matching the RAW fixture still matches the pruned one.

    Boundaries: the raw fixture and its ``prune_html`` snapshot are each loaded via set_content
    (offline); only selectors that match the raw DOM are required to survive pruning.
    On failure: ``prune_html`` stripped load-bearing markup - a REAL pruner bug. The assertion
    names the selector and fixture; fix the pruner rather than weakening this test.
    """
    raw = fixture.read_text(encoding="utf-8")
    selectors = {
        field: value
        for field, value in (
            (field, site_constants[site].get(field)) for field in sd.detail_selector_fields(site_constants[site])
        )
        if isinstance(value, str) and value
    }

    raw_counts = await _count_matches(chromium_browser, raw, selectors)
    matching = {field: selectors[field] for field, count in raw_counts.items() if count > 0}
    if not matching:
        pytest.skip(f"no current selector matches {site}/{fixture.stem}; nothing to preserve")

    pruned_counts = await _count_matches(chromium_browser, sd.prune_html(raw), matching)

    lost = [f"{field} ({matching[field]!r})" for field, count in pruned_counts.items() if count == 0]
    assert not lost, (
        f"prune_html dropped load-bearing markup for {site}/{fixture.stem}: "
        f"{', '.join(lost)} matched the raw fixture but not the pruned snapshot - fix the pruner."
    )
